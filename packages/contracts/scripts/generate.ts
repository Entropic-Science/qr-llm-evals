/**
 * JSON Schema → TypeScript types + zod validators for @qr-evals/contracts.
 *
 * Invoked by `python scripts/export_schemas.py` (never by hand):
 *
 *   node scripts/generate.ts --schema-dir <dir with _bundle.json + <Model>.json> --out-dir <src/generated>
 *
 * - `types.ts` is compiled from `_bundle.json` in one pass so nested models shared
 *   by several contracts (Provenance, ModelRef, …) get exactly one TypeScript name.
 * - `zod.ts` wraps each standalone `<Model>.json` with `z.fromJSONSchema` at
 *   module load, typed against `types.ts`. The JSON on disk is the single source
 *   of truth for both; there is no second code generator to keep in sync.
 *
 * Output is deterministic (same input bytes → same output bytes); the Python
 * side diffs it in `--check` mode.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { compile } from "json-schema-to-typescript";

const BANNER = `/* eslint-disable */
/**
 * GENERATED by scripts/export_schemas.py — do not edit.
 * Source: the pydantic models under backend/src/qr_llm_evals/<layer>/schema.py.
 */`;

function arg(name: string): string {
  const i = process.argv.indexOf(name);
  const v = i >= 0 ? process.argv[i + 1] : undefined;
  if (!v) throw new Error(`missing ${name}`);
  return resolve(v);
}

const schemaDir = arg("--schema-dir");
const outDir = arg("--out-dir");
mkdirSync(outDir, { recursive: true });

const bundle = JSON.parse(readFileSync(join(schemaDir, "_bundle.json"), "utf8")) as {
  properties: Record<string, unknown>;
};
// Contract names in registration order (the bundle's root properties).
const names = Object.keys(bundle.properties);

/**
 * pydantic titles every *property* ("Study Seed", "Id" …); json-schema-to-typescript
 * would hoist each into its own alias (`Id1`, `Model1`, …). Keep titles only where
 * they name a model (the root and each `$defs` entry) so those become the interfaces.
 */
function stripPropertyTitles(node: unknown, keepTitle: boolean): void {
  if (Array.isArray(node)) {
    for (const item of node) stripPropertyTitles(item, false);
    return;
  }
  if (node === null || typeof node !== "object") return;
  const obj = node as Record<string, unknown>;
  if (!keepTitle) delete obj.title;
  // json-schema-to-typescript predates `prefixItems` (2020-12); express pydantic's
  // fixed-length tuples in the draft-04 form it turns into TS tuples.
  if (Array.isArray(obj.prefixItems)) {
    obj.items = obj.prefixItems;
    obj.additionalItems = false;
    delete obj.prefixItems;
    delete obj.minItems;
    delete obj.maxItems;
  }
  for (const [key, value] of Object.entries(obj)) {
    if (key === "$defs" && value && typeof value === "object") {
      for (const def of Object.values(value as Record<string, unknown>)) stripPropertyTitles(def, true);
    } else {
      stripPropertyTitles(value, false);
    }
  }
}
stripPropertyTitles(bundle, true);

// ── types.ts ────────────────────────────────────────────────────────────────
const types = await compile(bundle as never, "Contracts", {
  bannerComment: BANNER,
  additionalProperties: false,
  strictIndexSignatures: true,
  unreachableDefinitions: true,
  unknownAny: true,
  ignoreMinAndMaxItems: true, // `T[]`, not `[T, ...T[]]`; zod enforces minItems at runtime
  format: true,
  style: { printWidth: 100, singleQuote: false, trailingComma: "all" },
});
writeFileSync(join(outDir, "types.ts"), types.replace(/\r\n/g, "\n"), "utf8");

// ── zod.ts ──────────────────────────────────────────────────────────────────
// Imports are relative to the *real* package layout (src/generated → ../../schema);
// the generator may be writing into a temporary tree, so compute the relative
// path from the requested out-dir to the requested schema-dir explicitly.
let rel = relative(outDir, schemaDir).replace(/\\/g, "/");
if (!rel.startsWith(".")) rel = `./${rel}`;

const lines: string[] = [
  BANNER,
  `import { z } from "zod";`,
  `import type * as T from "./types";`,
  ...names.map((n) => `import ${n}Json from "${rel}/${n}.json";`),
  "",
  "type Schema = z.core.JSONSchema.BaseSchema;",
  "",
  ...names.map(
    (n) =>
      `export const ${n}Schema = z.fromJSONSchema(${n}Json as unknown as Schema) as unknown as z.ZodType<T.${n}>;`,
  ),
  "",
  "/** Every contract name → its zod validator, in registration order. */",
  "export const schemas = {",
  ...names.map((n) => `  ${n}: ${n}Schema,`),
  "} as const;",
  "",
  "export type ContractName = keyof typeof schemas;",
  "",
];
writeFileSync(join(outDir, "zod.ts"), lines.join("\n"), "utf8");

console.log(`generated types.ts + zod.ts for ${names.length} contracts → ${outDir}`);
